// MARK: - Test Models

/// Parent model exercising `@Children`, `@Siblings`, and `@OptionalChild`.
final class House: Model, @unchecked Sendable {
    static let schema = "houses"
    static let space: String? = nil
    static let alias: String? = nil

    typealias IDValue = UUID

    @ID(key: .id)
    var id: UUID?

    @Field(key: "address")
    var address: String

    @Children(for: \.$house)
    var inhabitants: [Inhabitant]

    @OptionalChild(for: \.$house)
    var flagship: LandmarkInhabitant?

    @Siblings(through: HouseTag.self, from: \.$house, to: \.$tag)
    var tags: [Tag]

    required init() {}
}

/// A `@Children`-related model (has a `@Parent` back to `House`).
final class Inhabitant: Model, @unchecked Sendable {
    static let schema = "inhabitants"
    static let space: String? = nil
    static let alias: String? = nil

    typealias IDValue = UUID

    @ID(key: .id)
    var id: UUID?

    @Field(key: "name")
    var name: String

    @Field(key: "joined_at")
    var joinedAt: Date

    @Parent(key: "house_id")
    var house: House

    required init() {}
}

/// A `@OptionalChild`-related model (also used to test `@OptionalParent` from its side).
final class LandmarkInhabitant: Model, @unchecked Sendable {
    static let schema = "landmark_inhabitants"
    static let space: String? = nil
    static let alias: String? = nil

    typealias IDValue = UUID

    @ID(key: .id)
    var id: UUID?

    @Field(key: "title")
    var title: String

    @OptionalParent<House>(key: "house_id")
    var house: House?

    required init() {}
}

/// A pivot model for `@Siblings`.
final class HouseTag: Model, @unchecked Sendable {
    static let schema = "house_tags"
    static let space: String? = nil
    static let alias: String? = nil

    typealias IDValue = UUID

    @ID(key: .id)
    var id: UUID?

    @Parent(key: "house_id")
    var house: House

    @Parent(key: "tag_id")
    var tag: Tag

    required init() {}
}

/// The target of `@Siblings` (many-to-many).
final class Tag: Model, @unchecked Sendable {
    static let schema = "tags"
    static let space: String? = nil
    static let alias: String? = nil

    typealias IDValue = UUID

    @ID(key: .id)
    var id: UUID?

    @Field(key: "label")
    var label: String

    required init() {}
}

// MARK: - SQL Serialization Helpers

/// A minimal `Database` + `SQLDatabase` that only serializes SQL and never executes anything.
private final class EagerSerializerDB: Database, SQLDatabase {
    let logger = Logger(label: "test")
    let eventLoop: any EventLoop = NIOAsyncTestingEventLoop()
    let dialect: any SQLDialect = EagerPostgreSQLStyleDialect()
    let queryLogLevel: Logger.Level? = nil
    let context: DatabaseContext
    var inTransaction: Bool { false }

    init() {
        self.context = DatabaseContext(
            configuration: EagerConfig(),
            logger: Logger(label: "test"),
            eventLoop: NIOAsyncTestingEventLoop()
        )
    }

    func execute(sql query: any SQLExpression, _ onRow: @escaping @Sendable (any SQLRow) -> ()) -> EventLoopFuture<Void> {
        eventLoop.makeSucceededFuture(())
    }
    func execute(sql query: any SQLExpression, _ onRow: @escaping @Sendable (any SQLRow) -> ()) async throws {}

    func execute(query: DatabaseQuery, onOutput: @escaping @Sendable (any DatabaseOutput) -> ()) -> EventLoopFuture<Void> {
        eventLoop.makeSucceededFuture(())
    }
    func execute(schema: DatabaseSchema) -> EventLoopFuture<Void> { eventLoop.makeSucceededFuture(()) }
    func execute(enum: DatabaseEnum) -> EventLoopFuture<Void> { eventLoop.makeSucceededFuture(()) }
    func transaction<T>(_ closure: @escaping @Sendable (any Database) -> EventLoopFuture<T>) -> EventLoopFuture<T> { closure(self) }
    func withConnection<T>(_ closure: @escaping @Sendable (any Database) -> EventLoopFuture<T>) -> EventLoopFuture<T> { closure(self) }
}

/// Minimal PostgreSQL-style dialect so SQL serialization matches real Fluent output.
private struct EagerPostgreSQLStyleDialect: SQLDialect {
    var name: String { "psql" }
    var identifierQuote: any SQLExpression { SQLRaw("\"") }
    var literalStringQuote: any SQLExpression { SQLRaw("'") }
    var supportsAutoIncrement: Bool { true }
    var autoIncrementClause: any SQLExpression { SQLRaw("GENERATED BY DEFAULT AS IDENTITY") }
    var autoIncrementFunction: (any SQLExpression)? { nil }
    var literalDefault: any SQLExpression { SQLRaw("DEFAULT") }
    var supportsIfExists: Bool { true }
    var supportsDropBehavior: Bool { true }
    var supportsReturning: Bool { true }
    var triggerSyntax: SQLTriggerSyntax { .init() }
    var alterTableSyntax: SQLAlterTableSyntax { .init() }
    var upsertSyntax: SQLUpsertSyntax { .unsupported }
    var unionFeatures: SQLUnionFeatures { [] }
    var sharedSelectLockExpression: (any SQLExpression)? { SQLRaw("FOR SHARE") }
    var exclusiveSelectLockExpression: (any SQLExpression)? { SQLRaw("FOR UPDATE") }

    func bindPlaceholder(at position: Int) -> any SQLExpression { SQLRaw("$\(position)") }
    func literalBoolean(_ value: Bool) -> any SQLExpression { SQLRaw(value ? "true" : "false") }
    func customDataType(for: SQLDataType) -> (any SQLExpression)? { nil }
    func normalizeSQLConstraint(identifier: any SQLExpression) -> any SQLExpression { identifier }
    func nestedSubpathExpression(in column: any SQLExpression, for path: [String]) -> (any SQLExpression)? { nil }
}

/// Database configuration wiring an empty middleware array into the serializer DB.
private struct EagerConfig: DatabaseConfiguration {
    var middleware: [any AnyModelMiddleware] = []
    func makeDriver(for databases: Databases) -> any DatabaseDriver {
        struct D: DatabaseDriver {
            func makeDatabase(with context: DatabaseContext) -> any Database { EagerSerializerDB() }
            func shutdown() {}
        }
        return D()
    }
}

/// Serializes a `DatabaseQuery` to a SQL string via FluentSQL's converter.
private func serialize<M: FluentKit.Model>(_ query: QueryBuilder<M>) -> String {
    let converter = SQLQueryConverter(delegate: EagerConverterDelegate())
    let db = EagerSerializerDB()
    return db.serialize(converter.convert(query.query)).sql
}

/// Minimal delegate so the SQL converter can build without custom data types.
private struct EagerConverterDelegate: SQLConverterDelegate {
    func customDataType(_ kind: DatabaseSchema.DataType) -> (any SQLExpression)? { nil }
}

// MARK: - Tests

@Test("with + filter registers one eager loader")
func testFilteredWithRegistersLoader() {
    let db = EagerSerializerDB()
    let builder = House.query(on: db).with(\.$inhabitants) { inhabitants in
        inhabitants.filter(\.$joinedAt >= Date())
    }
    // One filtered loader should be pending on the builder after `.with(...)`.
    #expect(builder.eagerLoaders.count == 1)
}

@Test("Children: constraint is applied alongside the foreign key")
func filteredChildrenAppliesConstraint() {
    let db = EagerSerializerDB()
    let house = House()
    house.id = UUID()

    // Eager-load children, constraining the child query with a `joined_at` filter.
    let builder = House.query(on: db).with(\.$inhabitants) { children in
        children.filter(\.$joinedAt >= Date())
    }
    let loader = builder.eagerLoaders[0] as! FilteredEagerLoader<House, Inhabitant>

    // The serialized query must carry both the user filter and the FK back to `House`.
    let sql = serialize(loader.childQuery(models: [house], on: db))
    #expect(sql.contains(#""inhabitants"."joined_at""#))
    #expect(sql.contains(#">="#))
    #expect(sql.contains(#""inhabitants"."house_id""#))
}


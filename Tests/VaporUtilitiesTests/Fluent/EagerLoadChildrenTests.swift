// MARK: - Conflict / Coexistence Tests

@Test("Plain, filtered, and withDeleted loads coexist on one query")
func mixedWithOverloadsCoexist() {
    let db = EagerSerializerDB()
    let house = House()
    house.id = UUID()

    // Combine Fluent's plain `with(_:)`, its `with(_:withDeleted:)`, and the new filtered forms.
    let builder = House.query(on: db)
        .with(\.$flagship)
        .with(\.$inhabitants) { children in
            children.filter(\..$joinedAt >= Date())
        }
        .with(\.$tags, withDeleted: true)

    // Plain + filtered-children + withDeleted-tags == three eager loaders.
    #expect(builder.eagerLoaders.count == 3)

    // The filtered children loader still carries both filter and FK.
    let childrenLoader = builder.eagerLoaders[1] as! FilteredEagerLoader<House, Inhabitant>
    let sql = serialize(childrenLoader.childQuery(models: [house], on: db))
    #expect(sql.contains(#""inhabitants"."joined_at""#))
    #expect(sql.contains(#""inhabitants"."house_id""#))
}

@Test("Multiple filtered relations register independently")
func multipleFilteredRelationsRegister() {
    let db = EagerSerializerDB()
    let house = House()
    house.id = UUID()

    // Two distinct filtered relations chained on the same outer query.
    let builder = House.query(on: db)
        .with(\.$inhabitants) { children in
            children.filter(\.$joinedAt >= Date())
        }
        .with(\.$tags) { tags in
            tags.filter(\.$label == "featured")
        }

    // Each filtered relation registers its own loader; neither overwrites the other.
    #expect(builder.eagerLoaders.count == 2)

    // Serialize each loader independently and confirm both constraints surface.
    let childrenSQL = serialize((builder.eagerLoaders[0] as! FilteredEagerLoader<House, Inhabitant>)
        .childQuery(models: [house], on: db))
    let tagsSQL = serialize((builder.eagerLoaders[1] as! FilteredEagerLoader<House, Tag>)
        .childQuery(models: [house], on: db))
    #expect(childrenSQL.contains(#""inhabitants"."joined_at""#))
    #expect(tagsSQL.contains(#""tags"."label""#))
}

@Test("Filtered load with nil parent IDs still applies the user filter")
func filteredLoadWithNilParentIDDegrades() {
    let db = EagerSerializerDB()
    // No id is set: the FK predicate becomes an empty `IN ()` (serializer emits `WHERE 1 = 0`),
    // but the user's filter column must still appear in the query.
    let house = House()

    let builder = House.query(on: db).with(\.$inhabitants) { children in
        children.filter(\.$joinedAt >= Date())
    }
    let loader = builder.eagerLoaders[0] as! FilteredEagerLoader<House, Inhabitant>

    let sql = serialize(loader.childQuery(models: [house], on: db))
    // The user filter is present even though the parent FK set is empty.
    #expect(sql.contains(#""inhabitants"."joined_at""#))
}
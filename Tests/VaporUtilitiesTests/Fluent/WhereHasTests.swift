// MARK: - OR semantics

@Test("orWhereHas with no existing filters adds directly")
func testOrWhereHasNoExistingFilters() {
    let db = SerializerDB()
    let builder = Author.query(on: db)
        .orWhereHas(\.$posts) { post in post.filter(\.$status == "published") }
    let sql = serializeQuery(builder.query)
    // With no existing filters, OR is a no-op — just EXISTS
    #expect(sql.contains("EXISTS"))
    #expect(sql.contains(#""posts"."status""#))
}

@Test("orWhereHas with a parent filter produces (parent) OR EXISTS")
func testOrWhereHasWithParentFilter() {
    let db = SerializerDB()
    let builder = Author.query(on: db)
        .filter(\.$name == "Alice")
        .orWhereHas(\.$posts) { post in post.filter(\.$status == "published") }
    let sql = serializeQuery(builder.query)
    // Should produce: ("authors"."name" = $1) OR EXISTS (...)
    #expect(sql.contains("OR"))
    #expect(sql.contains(#""authors"."name""#))
    #expect(sql.contains("EXISTS"))
}

@Test("orWhereHas after whereHas produces (EXISTS A) OR (EXISTS B)")
func testOrWhereHasAfterWhereHas() {
    let db = SerializerDB()
    let builder = Author.query(on: db)
        .whereHas(\.$posts) { post in post.filter(\.$status == "published") }
        .orWhereHas(\.$posts) { post in post.filter(\.$status == "draft") }
    let sql = serializeQuery(builder.query)
    // Should produce: (EXISTS A) OR (EXISTS B)
    #expect(sql.contains("OR"))
    #expect(sql.contains("EXISTS"))
}

@Test("orWhereHas chained three times produces single OR group")
func testOrWhereHasChained() {
    let db = SerializerDB()
    let builder = Author.query(on: db)
        .whereHas(\.$posts) { post in post.filter(\.$status == "a") }
        .orWhereHas(\.$posts) { post in post.filter(\.$status == "b") }
        .orWhereHas(\.$posts) { post in post.filter(\.$status == "c") }
    let sql = serializeQuery(builder.query)
    // Should have a single OR group with 3 items, not nested groups
    #expect(sql.contains("OR"))
    #expect(sql.contains("EXISTS"))
}

@Test("orWhereHas with multiple parent filters produces (A AND B) OR EXISTS")

@Test("whereHas @Children with no closure generates EXISTS subquery")
func testWhereHasChildrenExistence() {
    let db = SerializerDB()
    let builder = Author.query(on: db).whereHas(\.$posts)
    let sql = serializeQuery(builder.query)
    #expect(sql.contains("EXISTS"))
    #expect(sql.contains("SELECT 1"))
    #expect(sql.contains(#""posts"."author_id""#))
    #expect(sql.contains(#""authors"."id""#))
}

